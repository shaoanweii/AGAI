function ScenarioPathBuilder({ paths, setPaths }) {
  function updatePath(index, field, value) {
    setPaths((current) => current.map((path, pathIndex) => pathIndex === index ? { ...path, [field]: value } : path));
  }

  function movePath(index, offset) {
    setPaths((current) => {
      const targetIndex = index + offset;
      if (targetIndex < 0 || targetIndex >= current.length) return current;
      const next = [...current];
      [next[index], next[targetIndex]] = [next[targetIndex], next[index]];
      return next;
    });
  }

  return <section className="scenario-path-builder" aria-labelledby="scenario-path-builder-title">
    <div className="scenario-path-builder-head">
      <div><strong id="scenario-path-builder-title">路径编排</strong><span>可设置调研执行顺序及每个路径的提示词</span></div>
      <button type="button" className="secondary small" onClick={() => setPaths((current) => [...current, { id: `route-${Date.now()}`, name: `调研路径 ${current.length + 1}`, prompt: '' }])}><Plus size={15} /> 新增路径</button>
    </div>
    <div className="scenario-path-list">
      {paths.map((path, index) => <article className="scenario-path-item" key={path.id}>
        <div className="scenario-path-order">{index + 1}</div>
        <div className="scenario-path-fields">
          <label>路径名称<input value={path.name} onChange={(event) => updatePath(index, 'name', event.target.value)} placeholder="例如：外观感知" /></label>
          <label>路径提示词<textarea value={path.prompt} onChange={(event) => updatePath(index, 'prompt', event.target.value)} placeholder="输入该路径的调研提示词" /></label>
        </div>
        <div className="scenario-path-actions" aria-label={`${path.name || `路径 ${index + 1}`} 操作`}>
          <button type="button" className="text-button" disabled={index === 0} onClick={() => movePath(index, -1)}>上移</button>
          <button type="button" className="text-button" disabled={index === paths.length - 1} onClick={() => movePath(index, 1)}>下移</button>
          <button type="button" className="text-button danger-text" disabled={paths.length === 1} onClick={() => setPaths((current) => current.filter((_, pathIndex) => pathIndex !== index))}>删除</button>
        </div>
      </article>)}
    </div>
  </section>;
}

