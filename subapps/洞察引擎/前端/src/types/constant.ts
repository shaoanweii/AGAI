/**
 * 导出类型
 * all: 导出全部
 * invalid: 导出无效
 * fail: 导出失败
 */
// eslint-disable-next-line @typescript-eslint/no-unused-vars
type DownLoadType = 'all' | 'invalid' | 'fail'

/**
 * 处理状态
 * 0: 未处理
 * 1: 处理中
 * 2: 已完成
 */
// eslint-disable-next-line @typescript-eslint/no-unused-vars
type HandleStatus = '0' | '1' | '2'
